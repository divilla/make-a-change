create function public.fn_change_insert(_project_id bigint, _ref_uuid uuid, _title text, _brief text) returns bigint
    language plpgsql
as
$$
declare
    _id       bigint;
    _modified timestamptz;
begin
    insert into public.change (project_id, ref_uuid, title)
    values ((select id from project where id = _project_id), _ref_uuid, _title)
    returning id, modified
        into _id, _modified;

    insert into public.doc (ref_id, ref_table, doc_type, body, created)
    values (_id, 'change', 'brief', _brief, _modified);

    return _id;
end;
$$;

drop procedure if exists public.sp_change_phase_update;
create procedure public.sp_change_phase_update(_change_id bigint, _phase text)
    language plpgsql
as
$$
begin
    update public.change
    set change_phase=_phase,
        modified=now()
    where id = _change_id;
end;
$$;

