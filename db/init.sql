create table public.change
(
    id           bigint generated by default as identity
        primary key,
    version      smallint                 default 0                 not null,
    ref_uuid     uuid                     default gen_random_uuid() not null,
    ref          integer,
    slug         text,
    project_id   bigint                                             not null references public.project (id),
    change_phase text                     default 'backlog'::text   not null,
    change_types text[]                   default ARRAY []::text[]  not null,
    epic_id      bigint,
    title        text                     default ''::text          not null,
    brief        text                     default ''::text          not null,
    spec         text                     default ''::text          not null,
    pr           text                     default ''::text          not null,
    pr_url       text                     default ''::text          not null,
    open         boolean                  default true              not null,
    done_tc      smallint                 default 0                 not null,
    total_tc     smallint                 default 0                 not null,
    completed    smallint generated always as (COALESCE(
            ((((100 * done_tc) / NULLIF(total_tc, 0))) ::smallint)::integer, 0)) stored,
