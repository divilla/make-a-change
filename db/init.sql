-- Serialize the dependency check with concurrent project writes; no Go transaction is needed.
create or replace function public.fn_config_delete(_slug text) returns boolean language plpgsql as $$
begin
 lock table public.project in share row exclusive mode;
 if exists(select 1 from public.project where config=_slug) then
  raise exception 'config is in use' using errcode='23503';
 end if;
 delete from public.config where slug=_slug;
 return found;
end;
$$;
