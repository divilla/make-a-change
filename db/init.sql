create procedure public.sp_change_title_update(_change_id bigint, _title text)
    language plpgsql
as
$$
begin
    update public.change
    set title=trim(regexp_replace(_title, '\s+', ' ', 'g')),
        modified=now()
    where id = _change_id;
end;
$$;

drop procedure if exists public.sp_project_doc_set;
create procedure public.sp_project_doc_set(_project_id bigint, _doc_type text, _body text, _agent_edit bool)
    language plpgsql
as
$$
begin
    update public.project
    set modified=now()
    where id=_project_id;

    if not found then
        return;
    end if;

    update public.doc set current=false where ref_id=_project_id and ref_table='project' and doc_type=_doc_type and current=true;

    insert into public.doc (ref_id, ref_table, doc_type, body, agent_edit)
    values (_project_id, 'project', _doc_type, _body, _agent_edit);
end;
$$;

