-- Parent UPDATE locks serialize appends for the same parent, including concurrent writers.
create or replace function public.fn_doc_insert(_ref_id bigint, _ref_table text, _doc_type text, _body text, _agent_edit bool)
returns bigint language plpgsql as $$
declare _id bigint;
begin
 case _ref_table
 when 'project' then update public.project set updated_at=now() where id=_ref_id;
 when 'epic' then update public.epic set updated_at=now() where id=_ref_id;
 when 'change' then update public.change set updated_at=now() where id=_ref_id;
 else raise exception 'invalid doc reference table' using errcode='22023';
 end case;
 if not found then return null; end if;
 update public.doc set current=false
 where ref_id=_ref_id and ref_table=_ref_table and doc_type=_doc_type and current;
 insert into public.doc(ref_id,ref_table,doc_type,body,agent_edit)
 values(_ref_id,_ref_table,_doc_type,_body,_agent_edit) returning id into _id;
 return _id;
end;
$$;

