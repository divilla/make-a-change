--- test_case ---

create function public.fn_test_case_insert(
    IN _change_id bigint,
    IN _scenario text
) returns bigint language plpgsql as
$$
declare
    _id       bigint;
    _version  smallint;
    _modified timestamptz;
begin
    perform 1
    from public.change
    where id = _change_id
        for no key update;

    if not found then
        raise exception 'Change % does not exist', _change_id
            using errcode = '23503'; -- foreign_key_violation
    end if;

    insert into public.test_case (change_id, scenario)
    values (_change_id, _scenario)
    returning id, version, modified into _id, _version, _modified;

    call public.sp_epic_test_case_recalculate(public.fn_change_test_case_recalculate(_change_id));
    call public.sp_test_case_to_history(
        _id, _version, _change_id, _scenario, _modified, false);

    return _id;
end;
$$;

create procedure public.sp_test_case_update_scenario(
    IN _id bigint,
    IN _scenario text
) language plpgsql as
$$
declare
    _version   smallint;
    _change_id bigint;
    _modified  timestamptz;
begin
    update public.test_case
    set version = version + 1,
        scenario = _scenario,
        modified = now()
    where id = _id
    returning version, change_id, modified
        into _version, _change_id, _modified;

    if not found then
        return;
    end if;

    call public.sp_test_case_to_history(
        _id, _version, _change_id, _scenario, now(), false);
end;
$$;

create or replace procedure public.sp_test_case_update_done(
    IN _id bigint,
    IN _done bool
) language plpgsql as
$$
declare
    _change_id bigint;
begin
    perform 1
    from public.change c
    where c.id = (
        select tc.change_id
        from public.test_case tc
        where tc.id = _id
    )
        for no key update;

    if not found then
        return;
    end if;

    update public.test_case
    set done = _done,
        modified = now()
    where id = _id
    returning change_id into _change_id;

    if not found then
        return;
    end if;

    call public.sp_epic_test_case_recalculate(
            public.fn_change_test_case_recalculate(_change_id));
end;
$$;

create or replace procedure public.sp_test_case_delete(IN _id bigint)
    language plpgsql as
$$
declare
    _scenario text;
    _version smallint;
    _change_id bigint;
begin
    perform 1
    from public.change c
    where c.id = (
        select tc.change_id
        from public.test_case tc
        where tc.id = _id
    )
        for no key update;

    if not found then
        return;
    end if;

    delete from public.test_case
    where id = _id
    returning version + 1, change_id, scenario
        into _version, _change_id, _scenario;

    if not found then
        return;
    end if;

    call public.sp_epic_test_case_recalculate(
            public.fn_change_test_case_recalculate(_change_id));

    call public.sp_test_case_to_history(
            _id, _version, _change_id, _scenario, now(), true);
end;
$$;

create procedure public.sp_epic_test_case_recalculate(IN _epic_id bigint)
    language plpgsql
as
$$
declare
    _done_tc smallint;
    _total_tc
             smallint;
begin
    perform 1
    from public.epic
    where id = _epic_id for no key update;

    select coalesce(sum(done_tc), 0),
           coalesce(sum(total_tc), 0)
    into
        _done_tc,
        _total_tc
    from public.change
    where epic_id = _epic_id;

    update public.epic
    set done_tc=_done_tc,
        total_tc=_total_tc
    where id = _epic_id;
end;
$$;

create function public.fn_change_test_case_recalculate(IN _change_id bigint)
    returns bigint
    language plpgsql as
$$
declare
    _epic_id bigint;
begin
    update public.change
    set done_tc = (select count(*) from public.test_case where change_id = _change_id and done),
        total_tc = (select count(*) from public.test_case where change_id = _change_id),
        modified = now()
    where id = _change_id
    returning epic_id into _epic_id;

    return _epic_id;
end;
$$;

create procedure public.sp_test_case_to_history(
    IN _id bigint,
    IN _version smallint,
    IN _change_id bigint,
    IN _scenario text,
    IN _modified timestamptz,
    IN _deleted boolean)
    language plpgsql as
$$
begin
    insert into public.test_case_history (id, version, change_id, scenario, modified, deleted)
    values (_id, _version, _change_id, _scenario, _modified, _deleted);
end;
$$;
