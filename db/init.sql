create function public.fn_change_insert(_project_id bigint, _ref_uuid uuid, _title text, _brief text) returns bigint
    language plpgsql
as
$$
declare
    _id       bigint;
    _modified timestamptz;
begin
    insert into public.change (project_id, ref_uuid, title, brief)
    values ((select id from project where id=_project_id), _ref_uuid, _title, _brief)
    returning id, modified
        into _id, _modified;

    insert into public.change_history (id, version, doc_type, body, agent_edit, modified)
    values (_id, 0, 'brief', _brief, false, _modified);

    return _id;
end;
$$;

