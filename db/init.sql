create or replace procedure public.sp_doc_active_set(_ref_table text, _ref_id bigint, _doc_type text, _doc_id bigint)
    language plpgsql as
$$
begin
    insert into public.doc_active (ref_table, ref_id, doc_type, doc_id)
    values (_ref_table, _ref_id, _doc_type, _doc_id)
    on conflict (ref_table, ref_id, doc_type) do update set doc_id=_doc_id;

    update public.doc set updated_by=0, updated_at=now(), deleted_by=null, deleted_at=null
    where id=_doc_id and deleted_by is not null;
end;
$$;

create or replace function public.fn_doc_insert(_ref_table text, _ref_id bigint, _doc_type text, _body text, _agent_edit bool)
    returns bigint
    language plpgsql as
$$
declare
    _doc_id bigint;
begin
    insert into public.doc(ref_id, ref_table, doc_type, body, agent_edit)
    values (_ref_id, _ref_table, _doc_type, _body, _agent_edit)
    returning id into _doc_id;

    call sp_doc_active_set(_ref_table, _ref_id, _doc_type, _doc_id);

    return _doc_id;
end;
$$;

