create procedure public.sp_change_assign_flow(_id bigint)
    language plpgsql
as
$$
declare
    _project_id bigint;
    _ref int;
    _slug text;
    _title text;
    _flow_stages text[];
    _flow_stage_modes text[];
begin
    select project_id, ref, slug, title into _project_id, _ref, _slug, _title from change where id=_id for update;

    if _ref is null then
        select flow_stages, flow_stage_modes_default into _flow_stages, _flow_stage_modes from config where slug='default';
        update public.project set last_ref=last_ref+1 where id=_project_id returning last_ref into _ref;
        update public.change set flow_stages=_flow_stages, flow_stage_modes=_flow_stage_modes where id=_id;
    end if;

    _slug=regexp_replace(lower(trim(_title)), '[^a-z0-9]+', '-', 'g');
    _slug=trim(both '-' from _slug);
    if _slug = '' then
        _slug='change';
    end if;
    _slug=concat(lpad(_ref::text, 3, '0'), '-', _slug);

    update public.change
    set ref=_ref, slug=_slug
    where id=_id;
end;
$$;



create function public.fn_change_start_run(_id bigint)
    returns uuid
    language plpgsql
as
$$
declare
    _claim_id uuid;
begin
    update public.change
    set
        run_claim_id=gen_random_uuid(),
        run_started_at=now()
    where
        id=_id and run_claim_id is null
    returning change.run_claim_id
        into _claim_id;

    return _claim_id;
end;
$$;



create function public.fn_change_update_run(_id bigint, _claim_id uuid, _flow_stage text, _task_step text, _task_status text, _run_error text, _run_is_completed bool)
    returns bigint
    language plpgsql
as
$$
declare
    _return_id bigint;
begin
    if _run_is_completed then
        update public.change
        set
            run_claim_id=null,
            run_flow_stage=_flow_stage,
            run_task_step=_task_step,
            run_task_status=_task_status,
            run_error=_run_error,
            run_is_completed=true,
            run_updated_at=now()
        where id=_id and run_claim_id=_claim_id
        returning id
            into _return_id;
    else
        update public.change
        set
            run_flow_stage=_flow_stage,
            run_task_step=_task_step,
            run_task_status=_task_status,
            run_error=_run_error,
            run_is_completed=false,
            run_updated_at=now()
        where id=_id and run_claim_id=_claim_id
        returning id
            into _return_id;
    end if;

    return _return_id;
end;
$$;



