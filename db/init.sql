create view public.vw_project as
SELECT p.id,
       p.name,
       (select count(*) from change c where c.project_id = p.id) AS change_count,
       p.created,
       p.modified
FROM project p
ORDER BY p.modified desc;

create view public.vw_epic as
SELECT e.id,
       e.project_id,
       e.name,
       (select count(*)
        from change c
                 join testcase tc on tc.change_id = c.id and tc.done = true
        where c.epic_id = e.id)                               as done_tc,
       (select count(*)
        from change c
                 join testcase tc on tc.change_id = c.id
        where c.epic_id = e.id)                               as total_tc,
       (select count(*) from change c where c.epic_id = e.id) AS change_count,
       e.created,
       e.modified
FROM epic e
ORDER BY e.project_id, e.name;

create view public.vw_change_list as
SELECT c.id,
       c.ref_uuid,
       c.ref,
       c.slug,
       c.project_id,
       c.change_phase,
       c.change_types,
       c.epic_id,
       e.name                                                                          AS epic_name,
       c.title,
       c.open,
       (select count(*) from testcase tc where tc.change_id = c.id and tc.done = true) as done_tc,
       (select count(*) from testcase tc where tc.change_id = c.id)                    as total_tc,
       c.modified
FROM change c
         LEFT JOIN epic e ON c.epic_id = e.id
ORDER BY c.project_id, c.modified DESC;

create view public.vw_change_details as
SELECT c.id,
       c.ref_uuid,
       c.ref,
       c.slug,
       c.project_id,
       c.change_phase,
       c.change_types,
       c.epic_id,
       e.name                                                                          AS epic_name,
       c.title,
       c.pr_url,
       c.open,
       (select count(*) from testcase tc where tc.change_id = c.id and tc.done = true) as done_tc,
       (select count(*) from testcase tc where tc.change_id = c.id)                    as total_tc,
       c.created,
       c.modified
FROM change c
         LEFT JOIN epic e ON c.epic_id = e.id
ORDER BY c.project_id, c.modified DESC;

create view public.vw_foreign_key as
SELECT conname             AS foreign_key_name,
       conrelid::regclass  AS table_name,
       confrelid::regclass AS referenced_table
FROM pg_constraint
WHERE contype = 'f'::"char"
  AND connamespace = 'public'::regnamespace::oid
ORDER BY (conrelid::regclass), conname;

