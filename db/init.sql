create procedure public.sp_epic_to_history(IN _id bigint, IN _deleted boolean)
    language plpgsql
as
$$
begin
    perform 1
    from public.epic
    where id = _id for no key update;

    insert into public.epic_history (id, version, project_id, name, modified, deleted)
    select id,
           version,
           project_id,
           name,
           modified,
           _deleted
    from public.epic
    where id = _id;
end;
$$;

