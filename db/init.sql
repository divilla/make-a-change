create procedure public.sp_epic_test_case_recalculate(IN _epic_id bigint)
    language plpgsql
as
$$
declare
    _done_tc smallint;
    _total_tc smallint;
begin
    if _epic_id is null then return; end if;

    select
        coalesce(sum(done_tc), 0),
        coalesce(sum(total_tc), 0)
    into
        _done_tc,
        _total_tc
    from public.change
    where epic_id=_epic_id;

    update public.epic
    set
        done_tc=_done_tc,
        total_tc=_total_tc
    where id=_epic_id;
end;
$$;

create procedure public.sp_change_test_case_recalculate(IN _change_id bigint)
    language plpgsql
as
$$
declare
    _epic_id bigint;
    _done_tc smallint;
    _total_tc smallint;
begin
    select count(*) into _done_tc from test_case where change_id=_change_id and done=true;
    select count(*) into _total_tc from test_case where change_id=_change_id;

    update public.change
    set
        done_tc=_done_tc,
        total_tc=_total_tc,
        modified=now()
    where id=_change_id;

    select epic_id into _epic_id from change where id=_change_id;
    call sp_epic_test_case_recalculate(_epic_id);
end;
$$;

create function public.fn_change_insert(_project_id bigint, _ref_uuid uuid, _title text, _def text) returns bigint
    language plpgsql
as
$$
declare
    _id bigint;
    _agent_edit bool;
    _modified timestamptz;
begin
    insert into public.change (
        project_id, ref_uuid, title, def
    ) values (
                 _project_id, _ref_uuid, _title, _def
             ) returning id, agent_edit, modified into _id, _agent_edit, _modified;

    insert into public.change_history (
        id, version, doc_type, body, agent_edit, modified
    ) values (
                 _id, 0, 'def', _def, false, _modified
             );

    return _id;
end;
$$;



