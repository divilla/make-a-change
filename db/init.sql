create or replace function public.fn_doc_comment_update(_id bigint, _body text)
    returns bigint
    language plpgsql as
$$
begin
    update public.doc
    set body=_body,
        updated_by=0,
        updated_at=now()
    where id = _id
      and doc_type = 'comment'
    returning id into _id;
    return _id;
end;
$$;

create or replace function public.fn_doc_delete(_id bigint)
    returns bigint
    language plpgsql as
$$
begin
    update public.doc
    set deleted_by=0,
        deleted_at=now()
    where id = _id
    returning id into _id;

    delete from public.doc_active where doc_id = _id;

    return _id;
end;
$$;
