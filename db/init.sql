create view public.vw_project_list as
SELECT p.id,
       p.name,
       (select count(*) from change c where c.project_id = p.id) AS change_count,
       p.active,
       p.created_by,
       p.updated_by,
       p.created_at,
       p.updated_at
FROM project p
ORDER BY p.active desc, p.updated_at desc;

create view public.vw_epic_list as
SELECT e.id,
       e.project_id,
       e.name,
       (select count(*)
        from change c
                 join testcase tc on tc.change_id = c.id and tc.done = true
        where c.epic_id = e.id)                               as done_tc,
       (select count(*)
        from change c
                 join testcase tc on tc.change_id = c.id
        where c.epic_id = e.id)                               as total_tc,
       (select count(*) from change c where c.epic_id = e.id) AS change_count,
       e.active,
       e.created_by,
       e.updated_by,
       e.created_at,
       e.updated_at
FROM epic e
ORDER BY e.project_id, e.name;

create view public.vw_change_list as
SELECT c.id,
       c.ref_uuid,
       (case when c.ref > 99 then c.ref::text else lpad(c.ref::text, 3, '0') end) || '-' || c.slug as ref_slug,
       c.project_id,
       c.change_phase,
       c.change_types,
       c.epic_id,
       e.name || ' (#' || c.epic_id || ')'                                                         AS epic_name,
       c.title,
       (select count(*) from testcase tc where tc.change_id = c.id and tc.done = true)             as done_tc,
       (select count(*) from testcase tc where tc.change_id = c.id)                                as total_tc,
       c.active,
       c.updated_at
FROM change c
         LEFT JOIN epic e ON c.epic_id = e.id
ORDER BY c.project_id, c.updated_at DESC;

create view public.vw_change_details as
SELECT c.id,
       c.ref_uuid,
       (case when c.ref > 99 then c.ref::text else lpad(c.ref::text, 3, '0') end) || '-' || c.slug as ref_slug,
       c.project_id,
       c.change_phase,
       c.change_types,
       c.epic_id,
       e.name                                                                                      AS epic_name,
       c.title,
       c.pr_url,
       c.after_change_id,
       ca.title || ' (#' || c.after_change_id::text || ')'                                         as after_change_name,
       c.active,
       (select count(*) from testcase tc where tc.change_id = c.id and tc.done = true)             as done_tc,
       (select count(*) from testcase tc where tc.change_id = c.id)                                as total_tc,
       c.created_by,
       c.updated_by,
       c.created_at,
       c.updated_at
FROM change c
         LEFT JOIN epic e ON c.epic_id = e.id
         LEFT JOIN change ca ON c.after_change_id = ca.id
ORDER BY c.project_id, c.updated_at DESC;

create view public.vw_doc_active as
select a.ref_table,
       a.ref_id,
       a.doc_type,
       a.doc_id,
       d.body,
       d.agent_edit,
       d.created_at,
       d.created_by,
       d.updated_at,
       d.updated_by,
       d.deleted_at,
       d.deleted_by
from doc_active a
         left join doc d on a.doc_id = d.id;

create view public.vw_foreign_key as
SELECT conname             AS foreign_key_name,
       conrelid::regclass  AS table_name,
       confrelid::regclass AS referenced_table
FROM pg_constraint
WHERE contype = 'f'::"char"
  AND connamespace = 'public'::regnamespace::oid
ORDER BY (conrelid::regclass), conname;

