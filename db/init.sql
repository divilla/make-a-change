create function public.fn_change_insert(_project_id bigint, _ref_uuid uuid, _title text, _brief text) returns bigint
    language plpgsql
as
$$
declare
    _id          bigint;
    _updated_at timestamptz;
begin
    insert into public.change (project_id, ref_uuid, title)
    values ((select id from project where id = _project_id), _ref_uuid, _title)
    returning id, updated_at
        into _id, _updated_at;

    insert into public.doc (ref_id, ref_table, doc_type, body, created_at)
    values (_id, 'change', 'brief', _brief, _updated_at);

    return _id;
end;
$$;

